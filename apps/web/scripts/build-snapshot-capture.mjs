import { build } from 'esbuild';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const entry = join(root, 'src/runtime/snapshot-dom-entry.ts');
const publicOut = join(root, 'public/od-snapshot-capture.js');
const inlineOut = join(root, 'src/runtime/snapshot-capture-inline.ts');

await build({
  entryPoints: [entry],
  bundle: true,
  format: 'iife',
  globalName: '__odSnapshotDomCapture',
  outfile: publicOut,
  platform: 'browser',
  target: ['es2020'],
  minify: true,
  legalComments: 'none',
});

const bundle = readFileSync(publicOut, 'utf8').replace(/<\/script/gi, '<\\/script');
writeFileSync(
  inlineOut,
  `// Generated by pnpm build:snapshot-capture — do not edit.\nexport const SNAPSHOT_DOM_CAPTURE_INLINE = ${JSON.stringify(bundle)};\n`,
  'utf8',
);
